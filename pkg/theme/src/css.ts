import {
  DEFAULT_APPEARANCE,
  buildPrePaintScript,
  computeThemeVars,
  resolveThemeState,
  roleToCssVar,
  type AppearanceConfig,
  type ComputeThemeVarsOptions,
} from './appearance'
import { BUILT_IN_THEME_IDS } from './palettes'

export { buildPrePaintScript, roleToCssVar }

/** Serialize a CSS custom-property map into a CSS declaration block. */
export function varsToCssBlock(
  vars: Readonly<Record<string, string>>,
  selector = ':root',
  colorScheme?: 'light' | 'dark',
): string {
  const lines: string[] = []
  if (colorScheme) {
    lines.push(`  color-scheme: ${colorScheme};`)
  }
  for (const [key, value] of Object.entries(vars)) {
    lines.push(`  ${key}: ${value};`)
  }
  return `${selector} {\n${lines.join('\n')}\n}`
}

export interface ThemeToCssOptions extends ComputeThemeVarsOptions {
  selector?: string
  osDark?: boolean
}

/** Generate a CSS rule block for any `AppearanceConfig`. */
export function themeToCss(
  config: Partial<AppearanceConfig> = DEFAULT_APPEARANCE,
  options?: ThemeToCssOptions,
): string {
  const osDark = options?.osDark ?? true
  const state = resolveThemeState(config, osDark, options?.customThemes)
  const vars = computeThemeVars(state.config, osDark, {
    customThemes: options?.customThemes,
  })
  const selector = options?.selector ?? `[data-theme="${state.resolvedThemeId}"]`
  return varsToCssBlock(vars, selector, state.appearance)
}

/**
 * Generate a complete static CSS stylesheet declaring `:root` (default Zen)
 * and `[data-theme="<id>"]` blocks for all 7 built-in Hanzo themes.
 */
export function generateThemesStylesheet(): string {
  const blocks: string[] = [
    '/* Generated by @hanzo/theme — canonical Hanzo theme stylesheets */',
    themeToCss({ ...DEFAULT_APPEARANCE, theme: 'zen' }, { selector: ':root' }),
  ]

  for (const id of BUILT_IN_THEME_IDS) {
    blocks.push(
      themeToCss(
        { ...DEFAULT_APPEARANCE, theme: id },
        { selector: `[data-theme="${id}"]` },
      ),
    )
  }

  return `${blocks.join('\n\n')}\n`
}

// ── Custom Theme CSS Remote-Fetch Security Guards ────────────────────────────

const FETCHES_BY_STRING = /image-set\(|\bsrc\(/i
const URL_NOT_LOCAL = /url\((?![ \t\n\f\r]*["']?(?:data:|#))/i
const URL_OR_STRING =
  /url\((?![ \t\n\f\r]*["'])[^)]*|url\([ \t\n\f\r]*("[^"\n\r\f]*"|'[^'\n\r\f]*')|"[^"\n\r\f]*"|'[^'\n\r\f]*'/gi

function withoutStrings(code: string): string {
  return code.replace(URL_OR_STRING, (token, urlString: string | undefined) => {
    if (urlString !== undefined) return /^["'](?:data:|#)/i.test(urlString) ? '' : 'url('
    return token.startsWith('"') || token.startsWith("'") ? '' : token
  })
}

function fetchesOutsideStrings(code: string): boolean {
  return FETCHES_BY_STRING.test(code) || URL_NOT_LOCAL.test(code)
}

/**
 * Whether a single CSS declaration value can load a remote resource.
 * Any backslash escape is conservatively refused because CSS escapes can spell
 * `url` or `var`.
 */
export function themeCssValueFetches(value: string): boolean {
  return value.includes('\\') || fetchesOutsideStrings(withoutStrings(value))
}

/**
 * Check whether custom theme CSS attempts to load remote resources via
 * `@import`, `image-set()`, `src()`, or non-`data:`/`#` `url()`.
 */
export function themeCssLoadsRemoteFiles(css: string): boolean {
  const code = withoutStrings(css.replace(/\/\*[\s\S]*?\*\//g, ''))
  return /@import/i.test(code) || fetchesOutsideStrings(code)
}
